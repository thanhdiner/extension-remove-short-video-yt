"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const os = require("node:os");
const path = require("node:path");
const { execFile } = require("node:child_process");
const { promisify } = require("node:util");
const { execute } = require("../terminal-host/git-extra-stash");
const run = promisify(execFile);

test("stash variants preserve changes, show patches and guard dropping all", async t => {
  const cwd = await fs.mkdtemp(path.join(os.tmpdir(), "editor-stash-test-"));
  t.after(async () => fs.rm(cwd, { recursive: true, force: true }));
  const git = async (dir, args) => (await run("git", ["--no-pager", "-c", "color.ui=false", ...args], { cwd: dir, windowsHide: true })).stdout;
  const call = (operation, options = {}) => execute({ operation, ...options }, { cwd, git, status: async () => ({ path: cwd }) });
  await git(cwd, ["init"]);
  await git(cwd, ["config", "user.email", "test@example.com"]);
  await git(cwd, ["config", "user.name", "Test"]);
  await git(cwd, ["config", "core.autocrlf", "false"]);
  await fs.writeFile(path.join(cwd, "tracked.txt"), "base\n");
  await git(cwd, ["add", "."]);
  await git(cwd, ["commit", "-m", "initial"]);
  await fs.writeFile(path.join(cwd, "tracked.txt"), "changed\n");
  await fs.writeFile(path.join(cwd, "new.txt"), "new content\n");
  await call("stashIncludeUntracked");
  assert.equal(await fs.readFile(path.join(cwd, "tracked.txt"), "utf8"), "base\n");
  await assert.rejects(fs.access(path.join(cwd, "new.txt")));
  const view = await call("stashView", { ref: "stash@{0}" });
  assert.match(view.output, /new content/);
  await assert.rejects(call("stashView", { ref: "--help" }), /Invalid stash reference/);
  await call("stashPopLatest");
  assert.equal(await fs.readFile(path.join(cwd, "new.txt"), "utf8"), "new content\n");
  await git(cwd, ["add", "tracked.txt"]);
  await call("stashStaged");
  assert.equal(await fs.readFile(path.join(cwd, "tracked.txt"), "utf8"), "base\n");
  await call("stashApplyLatest");
  assert.equal(await fs.readFile(path.join(cwd, "tracked.txt"), "utf8"), "changed\n");
  const hashes = (await git(cwd, ["stash", "list", "--format=%H"])).trim().split(/\r?\n/);
  await assert.rejects(call("stashDropAll", { confirmed: true, expectedHashes: [] }), /stash list changed/i);
  await assert.rejects(call("stashDropAll", { expectedHashes: hashes }), /Confirm/);
  await call("stashDropAll", { confirmed: true, expectedHashes: hashes });
  assert.equal((await git(cwd, ["stash", "list"])).trim(), "");
  assert.equal(await call("unsupported"), null);
});
