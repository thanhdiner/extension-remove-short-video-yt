// Run in an isolated ?workspaceTest tab against temporary fixture repositories.
// Set window.gitTestPaths to [seededRepoWithChanges, unbornRepo] first.
(async () => {
  if (!new URLSearchParams(location.search).get("workspaceTest") || !Array.isArray(window.gitTestPaths)) throw Error("Use isolated Git test fixtures");
  await localWorkspace.ready;
  const $ = id => document.getElementById(id);
  const assert = (ok, label) => { if (!ok) throw Error(label + ": " + $("git-status").textContent); };
  const wait = async predicate => { const until = Date.now() + 20000; while (!predicate()) { if (Date.now() > until) throw Error("Timed out: " + $("git-status").textContent); await new Promise(r => setTimeout(r, 40)); } };
  const idle = () => wait(() => $("git-panel").getAttribute("aria-busy") !== "true");
  const row = (name, staged) => [...document.querySelectorAll(".git-file")].find(row => row.dataset.path === name && row.dataset.staged === String(staged));
  const repoBody = index => [...document.querySelectorAll(".git-repo-body")].find(node => node.dataset.repo.toLowerCase() === window.gitTestPaths[index].toLowerCase());
  localSourceControl.setPaths(window.gitTestPaths);
  $("git-toggle").click(); await idle();
  assert(!$("git-panel").hidden && $("explorer-panel").hidden, "Source Control replaces Explorer");
  assert(document.querySelectorAll(".git-repository").length === 2, "two repositories detected");
  assert(row("tracked.txt", false) && row("new file.txt", false), "tracked and untracked changes shown");
  assert($("git-badge").textContent === "3", "combined change count");
  let message = repoBody(0).querySelector(".git-commit-form textarea"); message.value = "UI commit, staged only"; message.dispatchEvent(new Event("input"));
  assert(repoBody(0).querySelector('.git-commit-form button[type="submit"]').disabled, "cannot commit without staged changes");
  document.querySelectorAll(".git-repository > button:first-child")[1].click();
  assert(row("first.txt", false), "unborn repository selectable");
  document.querySelectorAll(".git-repository > button:first-child")[0].click();
  assert(repoBody(0).querySelector(".git-commit-form textarea").value === "UI commit, staged only", "per-repo commit draft retained");
  row("tracked.txt", false).querySelector("button").click();
  await wait(() => $("git-diff-dialog").open || $("git-status").classList.contains("error"));
  assert($("git-diff-dialog").open && $("git-diff-editor").querySelector(".monaco-diff-editor"), "opens Monaco diff");
  assert(monaco.editor.getModels().some(m => m.getValue().replace(/\r\n/g, "\n") === "old line\n") && monaco.editor.getModels().some(m => m.getValue().replace(/\r\n/g, "\n") === "new line\n"), "diff compares index and disk");
  $("git-diff-close").click(); await new Promise(r => setTimeout(r, 30));
  row("tracked.txt", false).querySelector("button:last-child").click(); await idle();
  assert(row("tracked.txt", true) && !row("tracked.txt", false), "stage moves file to staged group");
  row("tracked.txt", true).querySelector("button:last-child").click(); await idle();
  assert(!row("tracked.txt", true) && row("tracked.txt", false), "unstage restores working changes");
  row("tracked.txt", false).querySelector("button:last-child").click(); await idle();
  repoBody(0).querySelector('.git-commit-form button[type="submit"]').click(); await idle();
  assert(!row("tracked.txt", true) && row("new file.txt", false), "commit contains staged file only");
  assert(document.querySelector(".git-commit strong").textContent === "UI commit, staged only", "history refreshes after commit");
  assert(repoBody(0).querySelector(".git-commit-form textarea").value === "", "successful commit clears draft");
  document.querySelectorAll(".git-repository > button:first-child")[1].click();
  row("first.txt", false).querySelector("button:last-child").click(); await idle();
  message = repoBody(1).querySelector(".git-commit-form textarea"); message.value = "First UI commit"; message.dispatchEvent(new Event("input"));
  repoBody(1).querySelector('.git-commit-form button[type="submit"]').click(); await idle();
  assert(document.querySelector(".git-commit strong").textContent === "First UI commit", "first commit works");
  await localWorkspace.saveNow(); const idA = localWorkspace.current.id;
  assert((await localWorkspace.store.get(idA)).gitPaths.length === 2, "paths persisted in workspace");
  await localWorkspace.create("Git empty workspace"); await idle();
  assert(!localSourceControl.getPaths().length && !document.querySelector(".git-repository"), "workspace switch clears repositories");
  await localWorkspace.open(idA); await idle();
  assert(localSourceControl.getPaths().length === 2 && document.querySelectorAll(".git-repository").length === 2, "workspace restores repository list");
  sessionStorage.setItem("git-ui-regression", JSON.stringify({ idA, paths: window.gitTestPaths }));
  return { passed: true, repositories: 2, committedOnlyFixtureFiles: true };
})();
